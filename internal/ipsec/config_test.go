func TestChildName_RoundTrip(t *testing.T) {
	for _, tc := range []struct {
		conn  string
		epoch uint64
	}{
		{"egressa-gw-hk", 0},
		{"egressa-gw-hk", 7},
		{"a-e", 12},                      // connection name itself ending in "-e"
		{"x-e5", 18446744073709551615},   // max uint64, and a name containing "-e<digits>"
		{"egressa_gw-jp", 1234567890123}, // underscore
		{"a", 1},
	} {
		child := ChildName(tc.conn, tc.epoch)
		conn, epoch, ok := ParseChildName(child)
		if !ok || conn != tc.conn || epoch != tc.epoch {
			t.Errorf("ParseChildName(ChildName(%q, %d) = %q) = (%q, %d, %v)", tc.conn, tc.epoch, child, conn, epoch, ok)
		}
	}
}

func TestParseChildName_RejectsForeignNames(t *testing.T) {
	for _, name := range []string{"", "net-net", "egressa-gw-hk", "-e5", "gw-e", "gw-ex", "gw-e+5", "gw-e-5", "gw-e05", "gw-e99999999999999999999"} {
		if _, _, ok := ParseChildName(name); ok {
			t.Errorf("ParseChildName(%q) ok=true, want false", name)
		}
	}
}

func TestRender_SecretAlwaysHex(t *testing.T) {
	// strongSwan would read a verbatim secret starting with "0x" as hex
	// and "0s" as base64; rendering hex always removes that ambiguity.
	c := clientConn()
	c.PSK = "0xdeadbeefdeadbeef00"
	got, err := Render([]Connection{c})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(got, "secret = 0x3078646561646265656664656164626565663030\n") {
		t.Fatalf("PSK not rendered as the hex of its literal bytes:\n%s", got)
	}
	if strings.Contains(got, c.PSK) {
		t.Fatal("PSK appears verbatim in the rendered config")
	}
}

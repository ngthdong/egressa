// clientConn is a valid client-side connection used as the base for
// table-driven variations.
func clientConn() Connection {
	return Connection{
		Name:       "egressa-gw-hk",
		Epoch:      7,
		LocalAddr:  netip.MustParseAddr("192.0.2.1"),
		RemoteAddr: netip.MustParseAddr("192.0.2.2"),
		LocalID:    "client-1",
		RemoteID:   "gw-hk",
		Auth:       AuthPSK,
		PSK:        "s3cr3t-psk-value-0123",
		LocalTS:    []netip.Prefix{netip.MustParsePrefix("10.201.0.2/32")},
		RemoteTS:   []netip.Prefix{netip.MustParsePrefix("0.0.0.0/0")},
		IfID:       42,
		DPDDelay:   10 * time.Second,
	}
}

func gatewayConn() Connection {
	return Connection{
		Name:      "egressa-client-1",
		Epoch:     7,
		LocalAddr: netip.MustParseAddr("192.0.2.2"),
		LocalID:   "gw-hk",
		RemoteID:  "client-1",
		Auth:      AuthPSK,
		PSK:       "s3cr3t-psk-value-0123",
		LocalTS:   []netip.Prefix{netip.MustParsePrefix("0.0.0.0/0")},
		RemoteTS:  []netip.Prefix{netip.MustParsePrefix("10.201.0.2/32")},
		IfID:      43,
	}
}

func TestConnection_Validate_Valid(t *testing.T) {
	for name, c := range map[string]Connection{"client": clientConn(), "gateway": gatewayConn()} {
		if err := c.Validate(); err != nil {
			t.Errorf("%s: Validate() = %v, want nil", name, err)
		}
	}
	pk := clientConn()
	pk.Auth, pk.PSK, pk.LocalPubkey, pk.RemotePubkey = AuthPubkey, "", "client-1.pub", "gw-hk.pub"
	if err := pk.Validate(); err != nil {
		t.Errorf("pubkey: Validate() = %v, want nil", err)
	}
}

func TestConnection_Validate_Rejects(t *testing.T) {
	cases := map[string]func(*Connection){
		"empty name":         func(c *Connection) { c.Name = "" },
		"name with space":    func(c *Connection) { c.Name = "gw hk" },
		"name with brace":    func(c *Connection) { c.Name = "gw{hk" },
		"start needs remote": func(c *Connection) { c.RemoteAddr = netip.Addr{}; c.Start = StartStart },
		"mixed families":     func(c *Connection) { c.RemoteAddr = netip.MustParseAddr("2001:db8::2") },
		"zoned address": func(c *Connection) {
			c.LocalAddr = netip.MustParseAddr("fe80::1%eth0")
			c.RemoteAddr = netip.MustParseAddr("fe80::2")
		},
		"empty local id":         func(c *Connection) { c.LocalID = "" },
		"id with space":          func(c *Connection) { c.RemoteID = "gw hk" },
		"id injecting a section": func(c *Connection) { c.RemoteID = "gw}\n  evil {" },
		"short psk":              func(c *Connection) { c.PSK = "short" },
		"psk with quote":         func(c *Connection) { c.PSK = `aaaaaaaaaaaaaaaa"bbb` },
		"psk with backslash":     func(c *Connection) { c.PSK = `aaaaaaaaaaaaaaaa\bbb` },
		"psk with space":         func(c *Connection) { c.PSK = "aaaaaaaa aaaaaaaaaa" },
		"psk with newline":       func(c *Connection) { c.PSK = "aaaaaaaaaaaaaaaa\nsecret" },
		"unknown auth":           func(c *Connection) { c.Auth = "eap" },
		"pubkey path traversal":  func(c *Connection) { c.Auth = AuthPubkey; c.LocalPubkey = "../x.pub"; c.RemotePubkey = "gw.pub" },
		"no local ts":            func(c *Connection) { c.LocalTS = nil },
		"no remote ts":           func(c *Connection) { c.RemoteTS = nil },
		"invalid ts":             func(c *Connection) { c.RemoteTS = []netip.Prefix{{}} },
		"zero if_id":             func(c *Connection) { c.IfID = 0 },
		"bad proposal":           func(c *Connection) { c.ESPProposals = []string{"aes256gcm16 x25519"} },
		"negative dpd":           func(c *Connection) { c.DPDDelay = -time.Second },
		"unknown start":          func(c *Connection) { c.Start = "trap-ish" },
	}
	for name, mutate := range cases {
		c := clientConn()
		mutate(&c)
		if err := c.Validate(); err == nil {
			t.Errorf("%s: Validate() = nil, want an error", name)
		}
	}
}

func TestRender_ClientConnection_Golden(t *testing.T) {
	got, err := Render([]Connection{clientConn()})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	want := `# Generated by egressa (internal/ipsec). Do not edit by hand.
connections {
  egressa-gw-hk {
    version = 2
    local_addrs = 192.0.2.1
    remote_addrs = 192.0.2.2
    proposals = aes256gcm16-prfsha256-x25519
    dpd_delay = 10s
    local {
      auth = psk
      id = client-1
    }
    remote {
      auth = psk
      id = gw-hk
    }
    children {
      egressa-gw-hk-e7 {
        local_ts = 10.201.0.2/32
        remote_ts = 0.0.0.0/0
        esp_proposals = aes256gcm16-x25519
        mode = tunnel
        if_id_in = 42
        if_id_out = 42
        start_action = none
        dpd_action = clear
      }
    }
  }
}
secrets {
  ike-egressa-gw-hk {
    id-1 = client-1
    id-2 = gw-hk
    secret = 0x7333637233742d70736b2d76616c75652d30313233
  }
}
`
	if got != want {
		t.Fatalf("Render mismatch.\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestRender_GatewayAcceptsAnyRemote_NoDPD(t *testing.T) {
	got, err := Render([]Connection{gatewayConn()})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	for _, want := range []string{"remote_addrs = %any", "remote_ts = 10.201.0.2/32", "if_id_in = 43", "start_action = none"} {
		if !strings.Contains(got, want) {
			t.Errorf("rendered gateway config lacks %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"dpd_delay", "dpd_action"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("rendered gateway config has %q although DPDDelay is 0", unwanted)
		}
	}
}

func TestConnection_RemoteIDAny(t *testing.T) {
	c := gatewayConn()
	c.RemoteID = AnyID
	if err := c.Validate(); err != nil {
		t.Fatalf("Validate with RemoteID %%any: %v", err)
	}
	got, err := Render([]Connection{c})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(got, "id = %any") {
		t.Errorf("rendered config lacks the %%any remote id:\n%s", got)
	}
	c.LocalID = AnyID
	if err := c.Validate(); err == nil {
		t.Error("Validate accepted %any as the local identity")
	}
}

